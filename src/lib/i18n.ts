function translateGenerated(source: string): string | undefined {
	for (const [pattern, render] of DYNAMIC_GERMAN) {
		const match = source.match(pattern);
		if (match) return render(match);
	}
	return undefined;
}

function sourceHasAvailability(source: string): boolean {
	return source.includes('because of the availability you chose');
}

/** Resolve saved preferences first, then a browser locale, with English as the safe fallback. */
export function resolveLanguage(saved: unknown, browserLanguage?: string): Language {
	if (saved === 'en' || saved === 'de') return saved;
	return browserLanguage?.toLowerCase().split(/[-_]/)[0] === 'de' ? 'de' : 'en';
}

/** Translate UI copy without changing the source strings stored in a scenario. */
export function translate(source: string, language: Language, values: Record<string, string | number> = {}): string {
	let result = language === 'de' ? GERMAN[source] ?? translateGenerated(source) ?? source : source;
	for (const [key, value] of Object.entries(values)) result = result.replaceAll(`{${key}}`, String(value));
	return result;
}